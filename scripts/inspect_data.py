"""Inspect the datasets on disk and write verified facts to docs/DATA_NOTES.md.

Run this BEFORE training. It checks the assumptions the code makes:
  - ACRIMA: 705 images, 396 glaucoma, 309 normal; label inferred from '_g_' in the file name
  - REFUGE: which pixel values the masks contain (code assumes cup=0, disc=128, background=255)
"""
import argparse
from collections import Counter
from pathlib import Path

import numpy as np

import _bootstrap  # noqa: F401
from glaucoma.config import REPO_ROOT, data_path, load_config
from glaucoma.data.index import IMG_EXT, label_from_acrima_name
from glaucoma.preprocessing import load_image


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--config", default=None)
    a = p.parse_args()
    cfg = load_config(a.config)
    lines = ["# Data notes (generated by scripts/inspect_data.py)", ""]

    acrima = data_path(cfg, "acrima_dir")
    if acrima.exists():
        files = sorted(f for f in acrima.rglob("*") if f.suffix.lower() in IMG_EXT)
        labels = Counter(label_from_acrima_name(f.name) for f in files)
        sizes = Counter(load_image(f).shape[:2] for f in files[:50])
        ok = (len(files), labels[1], labels[0]) == (705, 396, 309)
        lines += ["## ACRIMA", f"- folder: `{acrima}`", f"- images: {len(files)} (expected 705)",
                  f"- glaucoma (name has `_g_`): {labels[1]} (expected 396)", f"- normal: {labels[0]} (expected 309)",
                  f"- formats: {sorted({f.suffix.lower() for f in files})}",
                  f"- sizes (first 50): {dict(list(sizes.most_common(5)))}",
                  f"- **matches the published counts: {'YES' if ok else 'NO. Check the folder and the _g_ naming rule'}**", ""]
    else:
        lines += ["## ACRIMA", f"- NOT FOUND at `{acrima}`. Run `python scripts/download_data.py`.", ""]

    refuge = data_path(cfg, "refuge_dir")
    if refuge.exists():
        imgs = sorted(refuge.rglob("*.jpg"))
        masks = sorted(m for m in refuge.rglob("*") if m.suffix.lower() in {".bmp", ".png"})
        vals = Counter()
        for m in masks[:30]:
            arr = np.array(load_image(m))[..., 0]
            vals.update(np.unique(arr).tolist())
        lines += ["## REFUGE", f"- folder: `{refuge}`", f"- jpg images: {len(imgs)}", f"- mask files: {len(masks)}",
                  f"- distinct mask pixel values (first 30 masks): {sorted(vals)}",
                  "- code assumes cup=0, disc=128, background=255. If the values above differ, edit "
                  "`masks_from_refuge` in `src/glaucoma/cdr.py`.", ""]
    else:
        lines += ["## REFUGE", f"- NOT FOUND at `{refuge}`. See docs/DATA.md.", ""]

    out = REPO_ROOT / "docs" / "DATA_NOTES.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))
    print(f"Saved to {out}")


if __name__ == "__main__":
    main()
